// Snapshot helper for the Family Planner migration.
//
// The migration reads production data out of the running app (see
// migration/DATABASE_MIGRATION.md), which produces one JSON file. This tool turns
// that JSON into D1 SQL, lists the stored-file objects, checks the encryption key
// against real ciphertext, and prints table counts. It never prints a secret value.
//
// Usage (run from the project root, Node 20+):
//   node migration/snapshot-tool.mjs counts        migration/out/snapshot-*.json
//   node migration/snapshot-tool.mjs sql           migration/out/snapshot-*.json migration/out/sql
//   node migration/snapshot-tool.mjs list-files    migration/out/snapshot-*.json
//   node migration/snapshot-tool.mjs decrypt-check migration/out/snapshot-*.json .secrets/field_key.txt
//
// Exit code 0 = success, 1 = the check failed or input was unusable.

import { readFileSync, writeFileSync, mkdirSync, existsSync, statSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { createDecipheriv } from 'node:crypto';

/* Tables that are migrated, in insert order (parents before children is not
   strictly required: the schema has no foreign keys). `sessions`, `auth_fails`
   and `rate_limits` are intentionally NOT migrated — see DATABASE_MIGRATION.md. */
const MIGRATION_TABLES = [
  'meta',
  'users',
  'credentials',
  'records',
  'changes',
  'notifications',
  'push_subs',
  'files',
  'ai_connections',
  'family_invites',
];

const CHUNK_STATEMENTS = 400;

function fail(message) {
  console.error(`ERROR: ${message}`);
  process.exit(1);
}

function loadSnapshot(path) {
  if (!path) fail('no snapshot file given');
  const abs = resolve(path);
  if (!existsSync(abs)) fail(`snapshot not found: ${abs}`);
  let raw;
  try {
    raw = readFileSync(abs, 'utf8');
  } catch (error) {
    fail(`cannot read ${abs}: ${error.message}`);
  }
  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    fail(`${basename(abs)} is not valid JSON (${error.message}) — a truncated download is the usual cause`);
  }
  if (!parsed || typeof parsed !== 'object' || !parsed.tables) {
    fail('snapshot has no "tables" object; is this really an export from /api/admin/snapshot?');
  }
  for (const name of MIGRATION_TABLES) {
    if (!Array.isArray(parsed.tables[name])) {
      fail(`snapshot is missing the "${name}" table array (found keys: ${Object.keys(parsed.tables).join(', ')})`);
    }
  }
  return parsed;
}

/* ------------------------------------------------------------------ counts */

function counts(snapshot) {
  const out = {};
  for (const name of MIGRATION_TABLES) out[name] = snapshot.tables[name].length;
  return out;
}

/* --------------------------------------------------------------- sql export */

function quote(value) {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) return 'NULL';
    return Number.isInteger(value) ? String(value) : String(value);
  }
  if (typeof value === 'boolean') return value ? '1' : '0';
  if (typeof value === 'object') value = JSON.stringify(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

function insertStatement(table, row) {
  const columns = Object.keys(row);
  if (!columns.length) return null;
  // INSERT OR REPLACE makes re-running an import idempotent instead of failing on
  // the primary key. Safe here: the destination is a fresh, empty database.
  const values = columns.map((c) => quote(row[c])).join(', ');
  const cols = columns.map((c) => `"${c}"`).join(', ');
  return `INSERT OR REPLACE INTO "${table}" (${cols}) VALUES (${values});`;
}

function writeSql(snapshot, outDir) {
  mkdirSync(outDir, { recursive: true });
  // The destination schema is created by the Worker itself on first request
  // (ensureSchema in src/store.js) — there is no migrations/ directory here.
  // So the dump only needs data, plus the schema version guard.
  const files = [];

  const header = [
    '-- Family Planner data import (generated by migration/snapshot-tool.mjs)',
    `-- Source export: ${snapshot.exportedAt || 'unknown'}`,
    `-- Source schema version: ${snapshot.schema || 'unknown'}`,
    '-- The destination Worker creates its tables on first request; this file only loads rows.',
  ].join('\n');

  let chunk = [];
  let index = 0;

  const flush = () => {
    if (!chunk.length) return;
    const name = `import-${String(index).padStart(3, '0')}.sql`;
    writeFileSync(join(outDir, name), `${header}\n\n${chunk.join('\n')}\n`, 'utf8');
    files.push({ name, statements: chunk.length });
    chunk = [];
    index += 1;
  };

  for (const table of MIGRATION_TABLES) {
    for (const row of snapshot.tables[table]) {
      const statement = insertStatement(table, row);
      if (!statement) continue;
      chunk.push(statement);
      if (chunk.length >= CHUNK_STATEMENTS) flush();
    }
  }
  flush();

  if (!files.length) fail('nothing to import: every table in the snapshot was empty');
  writeFileSync(
    join(outDir, 'manifest.json'),
    `${JSON.stringify({ source: snapshot.exportedAt || null, schema: snapshot.schema || null, counts: counts(snapshot), files }, null, 2)}\n`,
    'utf8',
  );
  return files;
}

/* -------------------------------------------------------------- file listing */

function listFiles(snapshot) {
  return snapshot.tables.files.map((row) => ({
    id: row.id,
    key: row.key,
    size: row.size,
    mime: row.mime,
    name: row.name,
  }));
}

/* ------------------------------------------------------------ key check */

function fieldKeyBytes(path) {
  if (!path) fail('no key file given');
  const abs = resolve(path);
  if (!existsSync(abs)) fail(`key file not found: ${abs}`);
  const raw = readFileSync(abs, 'utf8').trim();
  if (!raw) fail('the key file is empty');
  let bytes;
  try {
    bytes = Buffer.from(raw, 'base64');
  } catch {
    fail('the key file is not valid base64');
  }
  if (bytes.length !== 32) {
    fail(`the key file decodes to ${bytes.length} bytes, but AES-256-GCM needs exactly 32`);
  }
  return bytes;
}

/** Every `enc1:<iv b64>:<ciphertext b64>` string anywhere in the records table. */
function findCiphertexts(snapshot) {
  const found = [];
  const walk = (value, path) => {
    if (typeof value === 'string') {
      if (value.startsWith('enc1:')) found.push({ path, value });
      return;
    }
    if (Array.isArray(value)) {
      value.forEach((item, i) => walk(item, `${path}[${i}]`));
      return;
    }
    if (value && typeof value === 'object') {
      for (const [k, v] of Object.entries(value)) walk(v, `${path}.${k}`);
    }
  };
  snapshot.tables.records.forEach((row) => {
    let doc = row.doc;
    if (typeof doc === 'string') {
      try {
        doc = JSON.parse(doc);
      } catch {
        return;
      }
    }
    walk(doc, `records/${row.collection}/${row.id}`);
  });
  // ai_connections.api_key is stored in plaintext today, never as enc1 — nothing to do.
  return found;
}

function decryptCheck(snapshot, keyPath) {
  const ciphers = findCiphertexts(snapshot);
  if (!ciphers.length) {
    console.log('OK    the snapshot contains no enc1: values, so no key check is possible.');
    console.log('      This is expected on a database written before FIELD_KEY was set.');
    console.log('      The key still has to be set on the destination for future writes.');
    return true;
  }
  const key = fieldKeyBytes(keyPath);
  let okCount = 0;
  let badCount = 0;
  for (const item of ciphers.slice(0, 25)) {
    const parts = item.value.split(':');
    if (parts.length !== 3) {
      badCount += 1;
      console.log(`BAD   ${item.path}: malformed ciphertext`);
      continue;
    }
    try {
      const iv = Buffer.from(parts[1], 'base64');
      const data = Buffer.from(parts[2], 'base64');
      const tag = data.subarray(data.length - 16);
      const body = data.subarray(0, data.length - 16);
      const decipher = createDecipheriv('aes-256-gcm', key, iv);
      decipher.setAuthTag(tag);
      const plain = Buffer.concat([decipher.update(body), decipher.final()]).toString('utf8');
      okCount += 1;
      // Print only the field path and length — never the plaintext.
      console.log(`OK    ${item.path} decrypted (${plain.length} chars)`);
    } catch {
      badCount += 1;
      console.log(`BAD   ${item.path}: cannot decrypt with the key in ${basename(resolve(keyPath))}`);
    }
  }
  console.log(`\n${okCount} decrypted, ${badCount} failed, ${ciphers.length} ciphertext values in the snapshot.`);
  if (okCount > 0 && badCount === 0) {
    console.log('RESULT: this key matches the production data. Keep it.');
    return true;
  }
  console.log('RESULT: THIS KEY DOES NOT MATCH. Stop — do not cut over. Find the key that was set on 2026-11-03.');
  return false;
}

/* ----------------------------------------------------------------- entrypoint */

const [command, ...args] = process.argv.slice(2);
const startedAt = Date.now();

switch (command) {
  case 'counts': {
    const snapshot = loadSnapshot(args[0]);
    console.log(JSON.stringify({ exportedAt: snapshot.exportedAt || null, schema: snapshot.schema || null, counts: counts(snapshot) }, null, 2));
    break;
  }
  case 'sql': {
    const snapshot = loadSnapshot(args[0]);
    const outDir = resolve(args[1] || 'migration/out/sql');
    const files = writeSql(snapshot, outDir);
    const total = files.reduce((sum, f) => sum + f.statements, 0);
    console.log(`wrote ${files.length} SQL file(s), ${total} statements, to ${outDir}`);
    for (const file of files) console.log(`  ${file.name}  ${file.statements} statements`);
    break;
  }
  case 'list-files': {
    const snapshot = loadSnapshot(args[0]);
    const files = listFiles(snapshot);
    console.log(JSON.stringify(files, null, 2));
    if (!files.length) console.log('(no stored files: storage migration is a no-op)');
    break;
  }
  case 'decrypt-check': {
    const snapshot = loadSnapshot(args[0]);
    if (!decryptCheck(snapshot, args[1])) process.exitCode = 1;
    break;
  }
  default:
    fail(
      'unknown command. Use one of: counts | sql | list-files | decrypt-check\n' +
        'Example: node migration/snapshot-tool.mjs counts migration/out/snapshot-20260101T000000Z.json',
    );
}

console.log(`(finished in ${Date.now() - startedAt} ms)`);

