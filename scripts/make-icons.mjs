// Generates the PWA icons as real PNGs (no image libraries needed).

import { deflateSync } from 'node:zlib';
import { mkdir, writeFile } from 'node:fs/promises';

const NAVY = [27, 54, 93];
const WHITE = [255, 255, 255];
const TEAL = [15, 118, 110];

function crc32(buf) {
  let c;
  const table = new Int32Array(256);
  for (let n = 0; n < 256; n += 1) {
    c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    table[n] = c;
  }
  let crc = -1;
  for (let i = 0; i < buf.length; i += 1) crc = (crc >>> 8) ^ table[(crc ^ buf[i]) & 0xff];
  return (crc ^ -1) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const typeBuf = Buffer.from(type, 'ascii');
  const body = Buffer.concat([typeBuf, data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body), 0);
  return Buffer.concat([len, body, crc]);
}

function encodePng(size, pixel) {
  const raw = Buffer.alloc(size * (size * 4 + 1));
  let offset = 0;
  for (let y = 0; y < size; y += 1) {
    raw[offset] = 0;
    offset += 1;
    for (let x = 0; x < size; x += 1) {
      const [r, g, b, a] = pixel(x, y);
      raw[offset] = r;
      raw[offset + 1] = g;
      raw[offset + 2] = b;
      raw[offset + 3] = a;
      offset += 4;
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8;
  ihdr[9] = 6;
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 9 })),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

function insideRounded(x, y, size, radius) {
  const r = radius;
  if (x < r && y < r) return (x - r) ** 2 + (y - r) ** 2 <= r * r;
  if (x > size - r && y < r) return (x - (size - r)) ** 2 + (y - r) ** 2 <= r * r;
  if (x < r && y > size - r) return (x - r) ** 2 + (y - (size - r)) ** 2 <= r * r;
  if (x > size - r && y > size - r) return (x - (size - r)) ** 2 + (y - (size - r)) ** 2 <= r * r;
  return true;
}

/** Navy tile with a teal base line and three white bars (a rising finance chart). */
function icon(size, inset = 0) {
  const scale = (size - inset * 2) / 512;
  const origin = inset;
  const bars = [
    [150, 300, 64, 120],
    [236, 250, 64, 170],
    [322, 184, 64, 236],
  ];
  return (px, py) => {
    if (!insideRounded(px, py, size, size * 0.2)) return [0, 0, 0, 0];
    const x = (px - origin) / scale;
    const y = (py - origin) / scale;
    if (y >= 420 && y < 444 && x >= 132 && x < 404) return [...TEAL, 255];
    for (const [bx, by, bw, bh] of bars) {
      if (x >= bx && x < bx + bw && y >= by && y < by + bh) return [...WHITE, 255];
    }
    return [...NAVY, 255];
  };
}

export async function makeIcons() {
  await mkdir('web/public', { recursive: true });
  const small = encodePng(192, icon(192));
  const large = encodePng(512, icon(512));
  const maskable = encodePng(512, icon(512, 62));
  await writeFile('web/public/icon-192.png', small);
  await writeFile('web/public/icon-512.png', large);
  await writeFile('web/public/icon-maskable-512.png', maskable);
  // The hosting uploader only takes text/JS/JSON/WASM assets, so the Worker
  // serves the icons itself from these inlined copies.
  await writeFile(
    'src/icons.js',
    `// Generated by scripts/make-icons.mjs - do not edit.\nexport const ICONS = {\n  'icon-192.png': '${small.toString('base64')}',\n  'icon-512.png': '${large.toString('base64')}',\n  'icon-maskable-512.png': '${maskable.toString('base64')}',\n};\n`,
  );
}

if (import.meta.url === `file://${process.argv[1]?.replace(/\\/g, '/')}`) {
  await makeIcons();
  console.log('Icons written to web/public/');
}
